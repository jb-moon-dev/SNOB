  // ==============================================================
  // 화성시 행정구역 개편
  // ==============================================================

  static List<RegionQuery>? _getHwaseongMapping({
    required String regionName,
  }) {
    final bool isHwaseong =
        regionName.contains('화성시') ||
        regionName.contains('만세구') ||
        regionName.contains('효행구') ||
        regionName.contains('병점구') ||
        regionName.contains('동탄구');

    if (!isHwaseong) {
      return null;
    }

    // ------------------------------------------------------------
    // TourAPI
    //
    // 화성시       → 41 / 590
    // 만세구       → 41 / 591
    // 효행구       → 41 / 593
    // 병점구       → 41 / 595
    // 동탄구       → 41 / 597
    //
    // 집중률 API
    //
    // 기존 화성시  → 41 / 41590
    //
    // 따라서 모두 기존 화성시 집중률 데이터 사용
    // ------------------------------------------------------------

    return [
      RegionQuery(
        areaCd: '41',
        signguCd: '41590',
        regionName: regionName,
        reason: '화성시 및 신설 구 → 기존 화성시 집중률 데이터',
      ),
    ];
  }

