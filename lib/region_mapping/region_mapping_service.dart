  static List<RegionQuery> getQueryRegions({
    required String regionCode,
    required String sigunguCode,
    required String regionName,
  }) {
    final String normalizedName =
        _normalizeName(regionName);

    // ============================================================
    // 1. 인천 행정구역 개편
    // ============================================================

    final List<RegionQuery>? incheonQueries =
        _getIncheonMapping(
      regionName: normalizedName,
    );

    if (incheonQueries != null) {
      return incheonQueries;
    }

    // ============================================================
    // 2. 전남광주통합특별시
    // ============================================================

    final List<RegionQuery>? integratedQueries =
        _getIntegratedJeonnamGwangjuMapping(
      regionName: normalizedName,
    );

    if (integratedQueries != null) {
      return integratedQueries;
    }

    // ============================================================
    // 3. 화성시 행정구역 개편
    // ============================================================

    final List<RegionQuery>? hwaseongQueries =
        _getHwaseongMapping(
      regionName: normalizedName,
    );

    if (hwaseongQueries != null) {
      return hwaseongQueries;
    }

    // ============================================================
    // 4. 세종특별자치시
    // ============================================================

    if (regionCode == '36') {
      return [
        const RegionQuery(
          areaCd: '36',
          signguCd: '36110',
          regionName: '세종특별자치시',
          reason: '세종특별자치시 전체 지역 매핑',
        ),
      ];
    }

    // ============================================================
    // 5. 일반 지역
    // ============================================================

    final String sigunguName =
        _extractSigunguName(
      normalizedName,
    );

    final String? congestionSigunguCode =
        _findCongestionSigunguCode(
      regionCode: regionCode,
      sigunguName: sigunguName,
    );

    if (congestionSigunguCode == null) {
      print(
        '⚠️ 지역 매핑 실패'
        ' / $regionName'
        ' / TourAPI $regionCode-$sigunguCode',
      );

      return [];
    }

    return [
      RegionQuery(
        areaCd: _getCongestionAreaCode(
          regionCode: regionCode,
        ),
        signguCd: congestionSigunguCode,
        regionName: regionName,
        reason: '일반 지역명 기준 매핑',
      ),
    ];
  }

