  static String _extractSigunguName(
    String regionName,
  ) {
    final String normalized =
        _normalizeName(regionName);

    // ------------------------------------------------------------
    // 일반 시도명 제거
    // ------------------------------------------------------------

    const List<String> prefixes = [
      '서울특별시',
      '부산광역시',
      '대구광역시',
      '인천광역시',
      '광주광역시',
      '대전광역시',
      '울산광역시',
      '세종특별자치시',
      '경기도',
      '충청북도',
      '충청남도',
      '전라남도',
      '경상북도',
      '경상남도',
      '제주특별자치도',
      '강원특별자치도',
      '전북특별자치도',
    ];

    for (final String prefix in prefixes) {
      if (normalized.startsWith(prefix)) {
        return normalized
            .substring(prefix.length)
            .trim();
      }
    }

    return normalized;
  }

  // ==============================================================
  // 지역명 정규화
  // ==============================================================

  static String _normalizeName(
    String name,
  ) {
    return name
        .replaceAll(' ', '')
        .trim();
  }
