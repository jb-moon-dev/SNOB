import 'dart:convert';
import 'package:http/http.dart' as http;

void main() async {
  print('');
  print('============================================================');
  print('마포구 관광지 집중률 API 테스트');
  print('============================================================');

  // ============================================================
  // API 기본 정보
  // ============================================================

  const String baseUrl =
      'https://apis.data.go.kr/B551011/TatsCnctrRateService';

  const String serviceKey =
      'cbea666b85656aa336898b2d32bfee6f7d6fdad29e7c840109a41b9bf449c8a9';

  // ============================================================
  // 마포구 코드
  // ============================================================

  const String areaCd = '11';
  const String signguCd = '11440';

  print('');
  print('API 호출 시작');
  print('areaCd   = $areaCd');
  print('signguCd = $signguCd');

  // ============================================================
  // API 요청
  //
  // 중요:
  // baseYm 사용하지 않음
  // ============================================================

  final queryParameters = <String, String>{
    'serviceKey': serviceKey,
    'pageNo': '1',
    'numOfRows': '100',
    'MobileOS': 'ETC',
    'MobileApp': 'SNOB',
    'areaCd': areaCd,
    'signguCd': signguCd,
    '_type': 'json',
  };

  final uri = Uri.parse(
    '$baseUrl/tatsCnctrRatedList',
  ).replace(
    queryParameters: queryParameters,
  );

  print('');
  print('============================================================');
  print('요청 URL');
  print('============================================================');
  print(uri);

  // ============================================================
  // API 호출
  // ============================================================

  try {
    final response = await http.get(uri);

    print('');
    print('============================================================');
    print('API 응답');
    print('============================================================');

    print('STATUS CODE: ${response.statusCode}');
    print('');
    print(response.body);

    // ============================================================
    // HTTP 오류
    // ============================================================

    if (response.statusCode != 200) {
      print('');
      print('❌ HTTP 오류');
      print('상태 코드 : ${response.statusCode}');
      return;
    }

    // ============================================================
    // JSON 파싱
    // ============================================================

    dynamic decoded;

    try {
      decoded = jsonDecode(response.body);
    } catch (e) {
      print('');
      print('❌ JSON 파싱 실패');
      print(e);
      return;
    }

    // ============================================================
    // 최상위 응답 확인
    // ============================================================

    print('');
    print('============================================================');
    print('응답 구조 확인');
    print('============================================================');

    print('decoded type : ${decoded.runtimeType}');

    if (decoded is! Map) {
      print('❌ 최상위 응답이 Map이 아닙니다.');
      return;
    }

    print('최상위 필드 : ${decoded.keys.toList()}');

    // ============================================================
    // response 확인
    // ============================================================

    final responseData = decoded['response'];

    print('');
    print('response type : ${responseData.runtimeType}');

    if (responseData is! Map) {
      print('❌ response가 Map이 아닙니다.');
      return;
    }

    print('response 필드 : ${responseData.keys.toList()}');

    // ============================================================
    // header 확인
    // ============================================================

    final header = responseData['header'];

    print('');
    print('============================================================');
    print('HEADER');
    print('============================================================');

    if (header is Map) {
      print(header);
    } else {
      print('header 없음');
    }

    // ============================================================
    // body 확인
    // ============================================================

    final body = responseData['body'];

    print('');
    print('============================================================');
    print('BODY');
    print('============================================================');

    if (body is! Map) {
      print('❌ body가 Map이 아닙니다.');
      return;
    }

    print('body 필드 : ${body.keys.toList()}');

    // ============================================================
    // items 확인
    // ============================================================

    final itemsData = body['items'];

    print('');
    print('items type : ${itemsData.runtimeType}');
    print('items : $itemsData');

    // ============================================================
    // 데이터 없음
    // ============================================================

    if (itemsData == null || itemsData == '') {
      print('');
      print('❌ 마포구 관광지 집중률 데이터가 없습니다.');
      return;
    }

    if (itemsData is! Map) {
      print('');
      print('❌ items가 Map이 아닙니다.');
      return;
    }

    // ============================================================
    // item 확인
    // ============================================================

    final itemData = itemsData['item'];

    print('');
    print('item type : ${itemData.runtimeType}');

    if (itemData == null || itemData == '') {
      print('');
      print('❌ item이 없습니다.');
      return;
    }

    // ============================================================
    // item을 List로 통일
    // ============================================================

    List<Map<String, dynamic>> items = [];

    if (itemData is List) {
      items = itemData
          .map(
            (item) => Map<String, dynamic>.from(item),
          )
          .toList();
    } else if (itemData is Map) {
      items = [
        Map<String, dynamic>.from(itemData),
      ];
    } else {
      print('');
      print('❌ item의 형식을 확인할 수 없습니다.');
      return;
    }

    // ============================================================
    // 조회 결과
    // ============================================================

    print('');
    print('============================================================');
    print('조회 결과');
    print('============================================================');

    print('마포구 집중률 데이터 개수 : ${items.length}');

    if (items.isEmpty) {
      print('');
      print('❌ 마포구 관광지 집중률 데이터가 없습니다.');
      return;
    }

    // ============================================================
    // 모든 관광지 출력
    // ============================================================

    for (int i = 0; i < items.length; i++) {
      final data = items[i];

      print('');
      print('------------------------------------------------------------');
      print('[${i + 1}] 관광지 집중률 데이터');
      print('------------------------------------------------------------');

      // 전체 데이터
      print('전체 데이터:');
      print(data);

      // ----------------------------------------------------------
      // 관광지명
      // ----------------------------------------------------------

      print('');
      print('관광지명 후보:');

      print(
        'tAtsNm = ${data['tAtsNm']}',
      );

      print(
        'hubTatsNm = ${data['hubTatsNm']}',
      );

      print(
        'tatsNm = ${data['tatsNm']}',
      );

      // ----------------------------------------------------------
      // 관광지 코드
      // ----------------------------------------------------------

      print('');
      print('관광지 코드 후보:');

      print(
        'hubTatsCd = ${data['hubTatsCd']}',
      );

      print(
        'tAtsCd = ${data['tAtsCd']}',
      );

      print(
        'tatsCd = ${data['tatsCd']}',
      );

      // ----------------------------------------------------------
      // 지역 코드
      // ----------------------------------------------------------

      print('');
      print('지역 코드 후보:');

      print(
        'areaCd   = ${data['areaCd']}',
      );

      print(
        'signguCd = ${data['signguCd']}',
      );

      // ----------------------------------------------------------
      // 집중률
      // ----------------------------------------------------------

      print('');
      print('집중률 후보:');

      print(
        'cnctrRate = ${data['cnctrRate']}',
      );

      // ----------------------------------------------------------
      // 날짜
      // ----------------------------------------------------------

      print('');
      print('날짜 후보:');

      print(
        'baseYmd = ${data['baseYmd']}',
      );

      print(
        'baseYm = ${data['baseYm']}',
      );

      // ----------------------------------------------------------
      // 모든 필드명
      // ----------------------------------------------------------

      print('');
      print('모든 필드명:');
      print(data.keys.toList());
    }

    // ============================================================
    // 관광지명만 정리해서 출력
    // ============================================================

    print('');
    print('============================================================');
    print('마포구 관광지명 목록');
    print('============================================================');

    for (int i = 0; i < items.length; i++) {
      final data = items[i];

      final name =
          data['tAtsNm'] ??
          data['hubTatsNm'] ??
          data['tatsNm'] ??
          '이름 없음';

      final rate =
          data['cnctrRate'] ?? '집중률 없음';

      final date =
          data['baseYmd'] ?? '날짜 없음';

      print(
        '${i + 1}. $name | 집중률: $rate | 날짜: $date',
      );
    }

    // ============================================================
    // 최종 확인
    // ============================================================

    print('');
    print('============================================================');
    print('테스트 종료');
    print('============================================================');
  } catch (e, stackTrace) {
    print('');
    print('============================================================');
    print('❌ API 호출 중 예외 발생');
    print('============================================================');

    print(e);
    print('');
    print(stackTrace);
  }
}